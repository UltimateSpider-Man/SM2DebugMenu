"""Generate exact-build pins for the single-item held-slot assignment path."""
from pathlib import Path
import hashlib
import json
import struct
import sys

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "LTSC2019Compatibility/verification"))
from read_minidump import PE

SPANS = [
    (0x14ad240, 0x14ad252, "Native 12-byte request defaults: slot=-1, mode=5, flags=0"),
    (0x14aeda0, 0x14af1f5, "Single-item equip; already-owned branch avoids inventory transfer"),
    (0x14ad170, 0x14ad1b4, "Validate GameWeaponItem component handle and type"),
    (0x14b1750, 0x14b19fc, "Resolve configured held slot, replace only that slot, optionally select it"),
    (0x14b1a00, 0x14b1aaa, "Previous selection bookkeeping; retains inventory ownership"),
    (0x14b1b00, 0x14b1b4e, "Notify native equipment presentation"),
    (0x14b1b50, 0x14b1f82, "Reconcile held slots with HeroWeaponManager"),
    (0x34c0460, 0x34c050e, "Inventory asset-ID lookup"),
    (0x34b68e0, 0x34b6908, "Inventory activation predicate"),
    (0x14bd040, 0x14bd048, "GameWeaponItem embedded identity record"),
    (0x34b1350, 0x34b13d6, "Typed item configuration resolver"),
    (0x14bd640, 0x14bd6ce, "Typed WeaponConfigGame resolver"),
    (0x3093ec0, 0x3093f01, "Preloaded resource table lookup"),
    (0x29bd7b0, 0x29bd7e2, "Full twelve-bit component handle generation decoder"),
]


def main():
    pe = PE(ROOT / "Spider-Man2.exe")
    digest = hashlib.sha256(pe.data).hexdigest()
    if digest not in {
        "54215324e8c1e07c95c832a2d2d7b340d9028ca107ca4e5ad1072cd2809b7975",
        "01fea797e8c957018ccd01b8f5ecda99d4cea13036ee1ed2b06862340cf8a6e9",
    }:
        raise ValueError("Unsupported executable; refusing to generate pins")
    for vtable, slot, target in [(0x5478588, 0x198, 0x34c0460),
                                (0x5478588, 0x30, 0x34b68e0),
                                (0x547afa8, 0x120, 0x14bd040)]:
        assert struct.unpack("<Q", pe.at(vtable + slot, 8))[0] == pe.preferred_base + target
    assert pe.at(0x14ad240, 18) == bytes.fromhex("c701ffffffff488bc148c7410405000000c3")
    evidence, lines = [], []
    for start, end, meaning in SPANS:
        data = pe.at(start, end - start)
        assert len(data) <= 2048
        value = 14695981039346656037
        for byte in data:
            value = ((value ^ byte) * 1099511628211) & 0xffffffffffffffff
        lines.append(f"    {{0x{start:x},0x{len(data):x},0x{value:016x}ull}},")
        evidence.append({"start_rva": hex(start), "end_rva": hex(end),
                         "sha256": hashlib.sha256(data).hexdigest(), "fnv64": hex(value),
                         "contract": meaning})
    target = ROOT / "SM2DebugMenu/src/flame_slot_pins.inc"
    target.write_text("// Generated by SM2DebugMenu/tools/build_flame_slot_contract.py\n" +
                      "\n".join(lines) + "\n")
    folder = ROOT / "SM2DebugMenu/verification/mj-flame-equip-repair-20261114"
    folder.mkdir(parents=True, exist_ok=True)
    report = {"exe_sha256": digest, "spans": evidence,
              "options_hex": struct.pack("<iiBBBB", -1, 5, 1, 1, 0, 0).hex(),
              "held_slot_index": 2, "post_process_equip": False,
              "native_calls_executed": False, "gameplay_verified": False}
    (folder / "flame-slot-native-contract.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({"pins": len(lines), "exe_sha256": digest, "include": str(target)}))


if __name__ == "__main__":
    main()
